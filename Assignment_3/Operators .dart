
void main() {
  // a এবং b হলো Operand, কারণ এদের দিয়ে ভাগশেষ বের করা হয়।
  int a = 15;
  int b = 4;

  print("Addition: ${a + b}");
  // + হলো Operator, কারণ এটি যোগ করে।


  print("Subtraction: ${a - b}");
  // -  হলো Operator, কারণ এটি বিয়োগ করে।


  print("Multiplication: ${a * b}");
  // * হলো Operator, কারণ এটি গুণ করে।


  print("Division: ${a / b}");
  //  / হলো Operator, কারণ এটি ভাগ করে।


  print("Modulus: ${a % b}");
  // % হলো Operator, কারণ এটি ভাগশেষ বের করে।


}
